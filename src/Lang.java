  public static void set(int l) {
    if (l < 0 || l >= NLANG) l = ES;
    cur = l;
    switch (l) {
      case EN: tab = en(); break;
      case VI: tab = vi(); break;
      case VN: tab = strip(vi()); break;
      case PT: tab = pt(); break;
      case FR: tab = fr(); break;
      default: tab = es(); break;
    }
  }

  // detecta el idioma del telefono
  public static int detect() {
    String loc = null;
    try { loc = System.getProperty("microedition.locale"); } catch (Throwable t) {}
    if (loc == null || loc.length() < 2) return ES;
    String p = loc.substring(0, 2).toLowerCase();
    if (p.equals("es")) return ES;
    if (p.equals("vi")) return VI;
    if (p.equals("pt")) return PT;
    if (p.equals("fr")) return FR;
    return EN;
  }

