  static String sub(String s, String a, String b, String c) {
    int i = s.indexOf('{');
    if (i < 0) return s;
    StringBuffer sb = new StringBuffer();
    int from = 0;
    while (i >= 0 && i + 2 < s.length()) {
      sb.append(s.substring(from, i));
      char d = s.charAt(i + 1);
      sb.append(d == '0' ? a : (d == '1' ? b : c));
      from = i + 3;
      i = s.indexOf('{', from);
    }
    sb.append(s.substring(from));
    return sb.toString();
  }

  // quita las tildes del vietnamita (por si la fuente del telefono no las dibuja)
  static String[] strip(String[] src) {
    String[] r = new String[src.length];
    for (int i = 0; i < src.length; i++) {
      StringBuffer sb = new StringBuffer();
      for (int k = 0; k < src[i].length(); k++) {
        char c = src[i].charAt(k);
        int j = FROM.indexOf(c);
        sb.append(j >= 0 ? TO.charAt(j) : c);
      }
      r[i] = sb.toString();
    }
    return r;
  }

